DROP TABLE IF EXISTS PERCOBAAN_KUIS;
DROP TABLE IF EXISTS PESERTA_MAIN;
DROP TABLE IF EXISTS RUANG_MAIN;
DROP TABLE IF EXISTS BUTIR_SOAL;
DROP TABLE IF EXISTS CATATAN;
DROP TABLE IF EXISTS MATERI;
DROP TABLE IF EXISTS PENGGUNA;

-- 1. Tabel Pengguna
CREATE TABLE PENGGUNA
(
   ID_PENGGUNA           VARCHAR(36) NOT NULL,
   NAMA_PENGGUNA        VARCHAR(100) NOT NULL,
   EMAIL                 VARCHAR(150) NOT NULL UNIQUE,
   PASSWORD_HASH         VARCHAR(255) NOT NULL,
   TOTAL_XP              INT NOT NULL DEFAULT 0,
   STREAK_HARIAN         INT NOT NULL DEFAULT 0,
   TANGGAL_TERAKHIR_AKTIF DATE,
   AKUN_DIBUAT_PADA     TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
   PRIMARY KEY (ID_PENGGUNA)
);

-- 2. Tabel Folder Materi
CREATE TABLE MATERI
(
   ID_MATERI            VARCHAR(36) NOT NULL,
   ID_PENGGUNA          VARCHAR(36) NOT NULL,
   DESKRIPSI            TEXT,
   NAMA_MATERI          VARCHAR(50) NOT NULL,
   MATERI_DIBUAT_PADA   TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
   PRIMARY KEY (ID_MATERI),
   CONSTRAINT FK_MEMILIKI_MATERI FOREIGN KEY (ID_PENGGUNA)
      REFERENCES PENGGUNA (ID_PENGGUNA) ON DELETE CASCADE ON UPDATE CASCADE
);

-- 3. Tabel Catatan AI
CREATE TABLE CATATAN
(
   ID_CATATAN           VARCHAR(36) NOT NULL,
   ID_MATERI            VARCHAR(36) NOT NULL,
   JUDUL                VARCHAR(255) NOT NULL,
   JENIS_SUMBER         VARCHAR(20) NOT NULL,
   URL_BERKAS           TEXT,
   ISI_CATATAN          LONGTEXT NULL,
   ALUR_ROADMAP         JSON NULL,
   STATUS_PROSES        ENUM('MENUNGGU', 'SELESAI', 'GAGAL') DEFAULT 'MENUNGGU',
   IS_PUBLIK            BOOLEAN DEFAULT FALSE, -- TAMBAHAN FITUR SHARE PUBLIK
   PESAN_GALAT          TEXT NULL,
   CATATAN_DIBUAT_PADA  TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
   PRIMARY KEY (ID_CATATAN),
   CONSTRAINT FK_MENYIMPAN_CATATAN FOREIGN KEY (ID_MATERI)
      REFERENCES MATERI (ID_MATERI) ON DELETE CASCADE ON UPDATE CASCADE
);

-- 4. Tabel Soal Kuis
CREATE TABLE BUTIR_SOAL
(
   ID_SOAL              VARCHAR(36) NOT NULL,
   ID_CATATAN           VARCHAR(36) NOT NULL,
   PERTANYAAN           TEXT NOT NULL,
   PILIHAN_JAWABAN      JSON NOT NULL,
   JAWABAN_BENAR        INT NOT NULL,
   PEMBAHASAN           TEXT,
   PRIMARY KEY (ID_SOAL),
   CONSTRAINT FK_MENGHASILKAN_BUTIR_SOAL FOREIGN KEY (ID_CATATAN)
      REFERENCES CATATAN (ID_CATATAN) ON DELETE CASCADE ON UPDATE CASCADE
);

-- 5. Tabel Riwayat Percobaan Kuis Solo
CREATE TABLE PERCOBAAN_KUIS
(
   ID_PERCOBAAN         VARCHAR(36) NOT NULL,
   ID_PENGGUNA          VARCHAR(36) NOT NULL,
   ID_CATATAN           VARCHAR(36) NOT NULL,
   SKOR                 INT NOT NULL,
   XP_DIPEROLEH         INT NOT NULL,
   DIBUAT_PADA          TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
   PRIMARY KEY (ID_PERCOBAAN),
   CONSTRAINT FK_PERCOBAAN_PENGGUNA FOREIGN KEY (ID_PENGGUNA)
      REFERENCES PENGGUNA (ID_PENGGUNA) ON DELETE CASCADE ON UPDATE CASCADE,
   CONSTRAINT FK_PERCOBAAN_CATATAN FOREIGN KEY (ID_CATATAN)
      REFERENCES CATATAN (ID_CATATAN) ON DELETE CASCADE ON UPDATE CASCADE
);

-- 6. Tabel Ruang Arena Live
CREATE TABLE RUANG_MAIN
(
   ID_RUANG_MAIN        VARCHAR(36) NOT NULL,
   ID_PENGGUNA          VARCHAR(36) NOT NULL,
   ID_CATATAN           VARCHAR(36) NOT NULL,
   KODE_GAME            VARCHAR(6) NOT NULL,
   STATUS               VARCHAR(20) NOT NULL,
   RUANG_DIBUAT_PADA    TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
   PRIMARY KEY (ID_RUANG_MAIN),
   CONSTRAINT FK_DIGUNAKAN_DI_RUANG FOREIGN KEY (ID_CATATAN)
      REFERENCES CATATAN (ID_CATATAN) ON DELETE CASCADE ON UPDATE CASCADE,
   CONSTRAINT FK_MENJADI_HOST FOREIGN KEY (ID_PENGGUNA)
      REFERENCES PENGGUNA (ID_PENGGUNA) ON DELETE CASCADE ON UPDATE CASCADE
);

-- 7. Tabel Peserta Arena Live
CREATE TABLE PESERTA_MAIN
(
   ID_PESERTA           VARCHAR(36) NOT NULL,
   ID_RUANG_MAIN        VARCHAR(36) NOT NULL,
   ID_PENGGUNA          VARCHAR(36) NOT NULL,
   SKOR                 INT NOT NULL DEFAULT 0,
   LOG_JAWABAN          JSON NULL,
   PRIMARY KEY (ID_PESERTA),
   CONSTRAINT FK_PESERTA_RUANG FOREIGN KEY (ID_RUANG_MAIN)
      REFERENCES RUANG_MAIN (ID_RUANG_MAIN) ON DELETE CASCADE ON UPDATE CASCADE,
   CONSTRAINT FK_PESERTA_PENGGUNA FOREIGN KEY (ID_PENGGUNA)
      REFERENCES PENGGUNA (ID_PENGGUNA) ON DELETE CASCADE ON UPDATE CASCADE
);